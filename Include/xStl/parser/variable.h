#ifndef __TBA_XSTL_PARSER_VARIABLE_H
#define __TBA_XSTL_PARSER_VARIABLE_H

/**
 * @addtogroup xstl_parser
 * @{
 */

/**
 * @file variable.h
 * @brief Contains a code description of a variable.
 *
 * @details A variable has a type and a content.
 *
 * @author Elad Raz
 */
#include "xStl/types.h"
#include "xStl/data/string.h"
#include "xStl/parser/types.h"

/**
 * @brief This class represents a union of all known types.
 */
class BasicVariable
{
public:
    /**
     * @brief Default constructor. Creates integer variable.
     */
    BasicVariable();

    /**
     * @brief Constructor. Builds a variable of solid type.
     *
     * @param type The solid variable type
     */
    BasicVariable(Types::Type type);

    // Copy-constructor and operator = will be auto-generated by the compiler

    /**
     * @brief Return the type of the variable
     *
     * @return The type of the variable.
     */
    Types::Type getType() const;

    /**
     * @brief Return true if this variable type is a numeric one.
     *
     * @return True if this variable type is a numeric one.
     */
    bool isInteger() const;

    /**
     * @brief Return true if this variable type is string
     *
     * @return True if this variable type is string.
     */
    bool isString() const;

    /**
     * @brief Return true if this variable type is signed number
     *
     * @return True if this variable type is signed number.
     */
    bool isSignedInteger() const;

    /**
     * @brief Return true if this variable type is unsigned number
     *
     * @return True if this variable type is unsigned number.
     */
    bool isUnsignedInteger() const;

    /**
     * @brief Return the string content.
     *
     * @return The string content.
     * @throws cException for non-string types.
     */
    const cString& getString() const;

    /**
     * @brief Change the string content to 'other'
     *
     * @param other The string to replace with
     * @throws cException for non-string types.
     */
    void setString(const cString& other);

    /**
     * @brief Return the integer content of this variable.
     *
     * @return The integer content of this variable.
     * @throws cException for non-signed types.
     */
    int getSignedInteger() const;

    /**
     * @brief Change the content of the signed variable.
     *
     * @param other The integer to replace with
     * @throws cException for non-signed types.
     * @throws cException in case of overflow
     */
    void setSignedInteger(int other);

    /**
     * @brief Return the unsigned integer content of this variable.
     *
     * @return The unsigned integer content of this variable.
     * @throws cException for non-unsigned types.
     */
    uint getUnsignedInteger() const;

    /**
     * @brief Change the content of the unsigned variable.
     *
     * @param other The integer to replace with
     * @throws cException for non-unsigned types.
     * @throws cException in case of overflow
     */
    void setUnsignedInteger(uint other);

    /**
     * @brief Translate the variable into a string value.
     *
     * @return The string representation of the variable.
     */
    cString makeString() const;

private:
    /**
     * @brief The debug magic eye-catcher
     */
    static const uint32 EYE_CATCHER;

    /**
     * @brief The type of the variable
     */
    Types::Type m_type;

    /**
     * @brief The content of the variable
     */
    union {
        uint8   m_uint8;
        uint16  m_uint16;
        uint32  m_uint32;
        int8    m_int8;
        int16   m_int16;
        int32   m_int32;
    } m_data;

    /**
     * @brief The string object needs a unique handling (Due to ctors etc..)
     *    These avoid
     *   overflows.
     */
    cString m_string;
};


/**
 * @brief The variable with their names.
 */
class VariableType
{
public:
    /**
     * @brief Default ctor. Fills up the members.
     *
     * @param name The name of the variable.
     * @param data The value of the variable.
     */
    VariableType(const cString& name, const BasicVariable& data);
    // Copy constructor. operator = and default dtor will be generated by the
    // compiler.

    /**
     * @brief Return the name of the variable
     *
     * @return The name of the variable.
     */
    const cString& getName() const;

    /**
     * @brief Return the content of the variable for reading.
     *
     * @return The content of the variable for reading.
     */
    const BasicVariable& getData() const;

    /**
     * @brief Return the content of the variable for reading/writing.
     *
     * @return The content of the variable for reading/writing.
     */
    BasicVariable& getData();

private:
    /**
     * @brief The name of variable
     */
    cString m_name;
    /**
     * @brief The content of the variable and its name
     */
    BasicVariable m_data;
};


/** @} */
#endif // __TBA_XSTL_PARSER_VARIABLE_H
