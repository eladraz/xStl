#ifndef __TBA_STL_SETARRAY_H
#define __TBA_STL_SETARRAY_H

/**
 * @addtogroup xstl_data_containers
 * @{
 */

/**
 * @file setArray.h
 * @brief A single array of bits which define whether an attribute is set or
 *    not.
 *
 * @details A replacement data struct for the FD_ISSET methods.
 *
 * @author Elad Raz
 */
#include "xStl/types.h"
#include "xStl/data/array.h"

/**
 * @brief A single array of bits which define whether an attribute is set or
 *    not.
 *
 * @details A simple interface based on cSArray (instead of the more complex and
 *    powerful cBitStream)
 *
 * @note This data struct is optimized for 32 bit processors
 * @note This class is not thread safe
 */
class cSetArray {
public:
    /**
     * @brief Constructor. Initialize the array.
     *
     * @param initializedSize The number of values in the array.
     * @param shouldResetArray True to reset the values after the allocation.
     * @param resetAsSet If the array is reset, true to set all the values,
     *    false to clear them.
     */
    cSetArray(uint initializedSize = 0,
              bool shouldResetArray = true,
              bool resetAsSet = false);

    // Copy-constructor and operator = will be auto-generated by the compiler

    /**
     * @brief Return the number of values
     *
     * @return The number of values.
     */
    uint getLength() const;

    /**
     * @brief Changes the size of the values.
     *
     * @param newSize The number of values in the array.
     * @param saveContent Set to true if the previous content should be copied
     *    into the new array
     */
    void changeSize(uint newSize,
                    bool saveContent = true);

    /**
     * @brief Clear all values in the set
     */
    void resetArray();

    /**
     * @brief Return true if the value in 'location' is set.
     *
     * @param location The position of the bit to be tested
     * @return True if the value in 'location' is set.
     * @throws cException if the location is out of range.
     */
    bool isSet(uint location) const;

    /**
     * @brief Clears/set the value in 'location'
     *
     * @param location The position of the bit to be tested
     * @throws cException if the location is out of range.
     */
    void set(uint location);
    /**
     * @brief Clear the value in @a location.
     *
     * @param location The position of the bit to be cleared.
     * @throws cException if the location is out of range.
     */
    void clear(uint location);

    /**
     * @brief Returns the lowest location which is set If no bit is set, returns
     *   getLength()
     *
     * @return The lowest location which is set If no bit is set, returns
     *    getLength().
     */
    uint first() const;

    /**
     * @brief Return true if there is only a single place that is set in the
     *    setArray.
     *
     * @return True if there is only a single place that is set in the setArray.
     */
    bool isSetInOnePlace();

    /**
     * @brief AND the values of this set with the values of another set.
     *
     * @param other The set to AND with.
     * @return A pointer to this object.
     */
    cSetArray* operator&=(const cSetArray& other);

    /**
     * @brief OR the values of this set with the values of another set.
     *
     * @param other The set to OR with.
     * @return A pointer to this object.
     */
    cSetArray* operator|=(const cSetArray& other);

private:
    /**
     * @brief The number of values which can be stored, must be a multiple of 2
     */
    enum { BITS_COUNT_PER_ELEMENT = 32 };
    /**
     * @brief The shift value
     */
    enum { BITS_COUNT_PER_ELEMENT_SHIFT = 5 };
    /**
     * @brief The number of bytes per element
     */
    enum { BYTES_PER_ELEMENT_SHIFT = 2};

    /**
     * @brief Calculates the position of a value inside the array
     *
     * @param location The position of the value
     * @param arrayIndex The element index of which the value is stored
     * @param bitIndex The bits position inside the array
     */
    static void calculatePosition(uint location,
                                  uint& arrayIndex,
                                  uint& bitIndex);

    /**
     * @brief The content itself
     */
    cSArray<uint32> m_data;
    /**
     * @brief The number of values
     */
    uint m_length;
};


/** @} */
#endif // __TBA_STL_SETARRAY_H
