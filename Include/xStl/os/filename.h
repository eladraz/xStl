#ifndef __TBA_STL_OS_FILENAME_H
#define __TBA_STL_OS_FILENAME_H

/**
 * @addtogroup xstl_os
 * @{
 */

/**
 * @file filename.h
 * @brief The filename class is responsible for analyzing and performing actions
 *   over filenames.
 *
 * @details There are many file name formats; here is the list of all supported
 *   xStl name conventions:
 *   - DOS names    (A:\\FILENAME.EXT)
 *   - Win32 names  (C:\\Program files\\Internet explorer\\iexplore.exe)
 *   - Unix names   (/root/bin/parser)
 *   - http names   (http://localhost/index.html)
 *   - UNC names    (\\\\server\\c\\users\\tba\\projects\\database.ocx)
 *
 * @author Elad Raz
 */
#include "xStl/types.h"
#include "xStl/data/char.h"
#include "xStl/data/string.h"
#include "xStl/os/directoryFormatParser.h"

/**
 * @brief Cross-platform module which separates the file into the following two
 *   parts: \<fullpath\>\<filename\>
 *
 * @details These parts are also divided into the following groups:
 *   - Fullpath: database name, which is the drive name, database name, or
 *     internet site name which the file is located in.
 */
class cFilename {
public:
    /**
     * @brief Appendix constructor. Append a directory to a base directory
     *
     * @param basePath The path which the 'relativeFilenamePath' is based on.
     * @param relativeFilenamePath The relative name. Can be one of the
     *    following options: - Full path name (such as
     *    "C:\\windows\\notepad.exe") in this case the basePath is ignored if
     *    and only if the 'shouldStepBackward' is true or its path equals the
     *    filename path - Relative path (such as "a.txt" or "..\\a.txt") the
     *    cFilename class will parse the path directory according to the
     *    'basePath' NOTE: Different database names will now be excluded Giving
     *    a string ("D:temp.tmp") will throw exception.
     * @param shouldStepBackward Security flag. If its value equals true, the
     *    full file path (base+relative) should be able to access files at the
     *    parent directory. Otherwise, if this value is false, the file must
     *    start with the 'basePath'.
     * @param enforceDirectory Set to true in order to enforce directory
     * @throws cException if the directory format is invalid
     */
    cFilename(const cFilename& basePath,
              const cString& relativeFilenamePath,
              bool shouldStepBackward = true,
              bool enforceDirectory = false);

    // Copy constructor and operator = will be auto-generated by the compiler.

    // Operator == and operator != will be auto-generated by the compiler.

    /**
     * @brief Return the complete path of the file including its base directory,
     *    file
     *   name and file extension.
     *
     * @return The complete path of the file including its base directory, file
     *    name and file extension.
     * @note If the filename is empty, the returned string is a directory. The
     *    directory must end with a directory marker (such as '\\' or '/')
     */
    const cString& getFullPath() const;

    /**
     * @brief Return the database name of the file.
     *
     * @details - For windows/DOS based filename the return value is a drive
     *    name (C:, A:)
     *   - For internet site, the return value will be the name of the service,
     *   such as "http:", "ftp:", "https:".
     *   - UNC name will have the following syntax: \\\\servername\\devicename\\
     *
     * @return The database name of the file.
     */
    cString getDatabaseName() const;

    /**
     * @brief Return the directory of the file.
     *
     * @details The directory contains the base position of the file, including
     *    it's database name.
     *
     * @return The directory of the file.
     */
    cFilename getDirectoryName() const;

    /**
     * @brief Returns only the portion of the filename Returns empty string if
     *    the
     *   filename is not included.
     *
     * @return Only the portion of the filename.
     */
    cString getFilename() const;

    /**
     * @brief Return the temporary directory of the current operating system.
     *
     * @details This directory has read/write attributes and is used to store
     *   temporary application data.
     *
     * For windows, this is the cFilename wrappers of the GetTempDir() win32 API
     *
     * @return The temporary directory of the current operating system.
     */
    static const cFilename& getTempDirectory();

    /**
     * @brief Return the current directory of the computer at this moment.
     *
     * @return The current directory of the computer at this moment.
     */
    static cFilename getCurrentDirectory();

    /**
     * @brief Tests whether a character is a directory separator.
     *
     * @param ch The separator to be examined.
     * @return True if ch is a separator.
     */
    static bool isDirectorySeparator(const character ch);

    /**
     * @brief Return a string which start from 'startPosition' and last until
     *    the next
     *   directory separator or the end of the string
     *
     * @param filename The filename to extract the information from
     * @param startPosition The start position for the string search
     * @return A string which start from 'startPosition' and last until the next
     *    directory separator or the end of the string.
     */
    static cString readDirectory(const cString& filename,
                                 uint startPosition);

    /**
     * @brief Return true if the 'directoryName' marks a previous directory
     *    operation
     *
     * @return True if the 'directoryName' marks a previous directory operation.
     * @param directoryName The directory name to test.
     */
    static bool isPreviousDirectoryMarker(const cString& directoryName);

    /**
     * @brief Return true if the 'directoryName' marks the current directory
     *    operation
     *
     * @return True if the 'directoryName' marks the current directory
     *    operation.
     * @param directoryName The directory name to test.
     */
    static bool isCurrentDirectoryMarker(const cString& directoryName);

    /**
     * @brief Check the relative directory name.
     *
     * @details Check any illegal characters of the directory. The function
     *    prevents any future buffer-overflow related to file names.
     *
     * @param relativeName The name to be checked
     * @return True if the name is valid file/directory name, false otherwise.
     */
    static bool checkRelativeNameValidation(const cString& relativeName);

    /// The directory separator used by Microsoft operating system ('\')
    static const character m_directorySeparatorWindows;
    /// The directory separator used by Unix based operating system ('/')
    static const character m_directorySeparatorUnix;
private:
    /**
     * @brief Make a filename class using a full-path name.
     *
     * @details The format of the filename changes along with the operating
     *    system.
     *
     * @param fullpath The complete file path including its database
     * @param parser The object to be used in order to parse the content of the
     *    filename
     */
    cFilename(const cString& fullpath,
              const cDirectoryFormatParser::FilenameParserPtr& parser);

    /**
     * @brief Make sure that the filename ends with directory separator
     */
    void enforceDirectory();

    /**
     * @brief The complete path of the filename, not including the filename
     *    itself and
     *   its file extension.
     *
     * @details For example: C:\\WINNT\\System32\\drivers\\ndis.sys
     */
    cString m_filename;

    /**
     * @brief The object to be used in order to parse the content of the
     *    filename
     */
    cDirectoryFormatParser::FilenameParserPtr m_directoryParser;

    /// A directory which points to the current directory
    static const character m_directoryCurrentDirectory[];
    /// A directory which points to the previous directory
    static const character m_directoryPreviousDirectory[];
    /// List of all operating system directory object handlers.
    enum { OS_DIRECTORY_FORMAT_PARSER_COUNT = 1};
    static cDirectoryFormatParserPtr
        m_directoryParserHandlers[OS_DIRECTORY_FORMAT_PARSER_COUNT];
};


/** @} */
#endif // __TBA_STL_OS_FILENAME_H
