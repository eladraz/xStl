/*
 * test_operators.cpp
 *
 * Test the operators generated by MAKE_SIMPLE_OPERATORS, for a total order
 * and for a partial order.
 *
 * Author: Elad Raz <e@eladraz.com>
 */
#include "xStl/types.h"
#include "xStl/operators.h"
#include "xStl/data/list.h"
#include "tests.h"

/*
 * A point which is smaller than another point only if both of its
 * coordinates are smaller or equal (a partial order).
 */
class cTestPartialPoint
{
public:
    cTestPartialPoint(int x, int y) : m_x(x), m_y(y) {}

    bool operator == (const cTestPartialPoint& other) const
    {
        return (m_x == other.m_x) && (m_y == other.m_y);
    }

    bool operator < (const cTestPartialPoint& other) const
    {
        return (m_x <= other.m_x) && (m_y <= other.m_y) && !(*this == other);
    }

    MAKE_SIMPLE_OPERATORS(cTestPartialPoint);

private:
    int m_x;
    int m_y;
};

/*
 * A number (a total order)
 */
class cTestNumber
{
public:
    cTestNumber(int value) : m_value(value) {}
    bool operator == (const cTestNumber& other) const { return m_value == other.m_value; }
    bool operator <  (const cTestNumber& other) const { return m_value <  other.m_value; }
    MAKE_SIMPLE_OPERATORS(cTestNumber);

private:
    int m_value;
};

class cTestOperators : public cTestObject
{
public:
    void testTotalOrder()
    {
        for (int a = -2; a <= 2; a++)
        {
            for (int b = -2; b <= 2; b++)
            {
                TESTS_ASSERT_EQUAL(cTestNumber(a) != cTestNumber(b), a != b);
                TESTS_ASSERT_EQUAL(cTestNumber(a) >  cTestNumber(b), a >  b);
                TESTS_ASSERT_EQUAL(cTestNumber(a) >= cTestNumber(b), a >= b);
                TESTS_ASSERT_EQUAL(cTestNumber(a) <= cTestNumber(b), a <= b);
            }
        }
    }

    void testPartialOrder()
    {
        // Not 'small': <windows.h> defines it as a macro
        cTestPartialPoint low(1, 1);
        cTestPartialPoint high(2, 2);
        cTestPartialPoint wide(2, 1);
        cTestPartialPoint tall(1, 2);

        TESTS_ASSERT(high > low);
        TESTS_ASSERT(high >= low);
        TESTS_ASSERT(low <= high);
        TESTS_ASSERT(!(low > high));
        TESTS_ASSERT(low >= low);
        TESTS_ASSERT(low <= low);
        TESTS_ASSERT(!(low > low));

        // 'wide' and 'tall' are incomparable: no ordering operator is true
        TESTS_ASSERT(!(wide < tall));
        TESTS_ASSERT(!(wide > tall));
        TESTS_ASSERT(!(tall > wide));
        TESTS_ASSERT(!(wide >= tall));
        TESTS_ASSERT(!(wide <= tall));
        TESTS_ASSERT(wide != tall);
    }

    // cList iterators: < must be strict, so an iterator isn't greater than itself
    void testListIterators()
    {
        cList<int> list;
        list.append(1);
        list.append(2);
        cList<int>::iterator first = list.begin();
        cList<int>::iterator second = list.begin();
        ++second;

        TESTS_ASSERT(first < second);
        TESTS_ASSERT(second > first);
        TESTS_ASSERT(!(first < first));
        TESTS_ASSERT(!(first > first));
        TESTS_ASSERT(first >= first);
        TESTS_ASSERT(first <= first);
        TESTS_ASSERT(!(second < first));
    }

    // Perform the test
    virtual void test()
    {
        testTotalOrder();
        testPartialOrder();
        testListIterators();
    }

    // Return the name of the module
    virtual cString getName() { return __FILE__; }
};


// Instance test object
cTestOperators g_globalTestOperators;
